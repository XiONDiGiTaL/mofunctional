/**
 * Cache-busting for the live site. The CDN keeps JS for hours, so a returning player could run
 * an old phone.js against a new main.js (or miss a whole new module). This writes an import map
 * into index.html that sends every module URL to `?v=<content hash>`, and stamps the entry
 * script and stylesheets the same way: a file that changed gets a new URL, one that did not
 * stays cached.
 *
 *   node scripts/stamp.mjs          rewrite index.html
 *   node scripts/stamp.mjs --check  exit 1 if index.html is out of date (used by npm run check)
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// line endings are ignored so a Windows checkout (CRLF) stamps the same as the repo (LF)
const hash = (p) => createHash('sha1').update(readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n')).digest('hex').slice(0, 10);

function walk(dir, out = []) {
  for (const name of readdirSync(join(root, dir))) {
    const p = join(dir, name);
    if (statSync(join(root, p)).isDirectory()) walk(p, out);
    else if (name.endsWith('.js')) out.push(p.split('\\').join('/'));
  }
  return out;
}

export function stamped() {
  const imports = {};
  for (const p of [...walk('src'), ...walk('vendor')].sort()) imports[`./${p}`] = `./${p}?v=${hash(p)}`;
  const map = `<!-- stamp:begin (generated by scripts/stamp.mjs — do not edit) -->
<script type="importmap">
${JSON.stringify({ imports }, null, 1)}
</script>
<!-- stamp:end -->`;
  let html = readFileSync(join(root, 'index.html'), 'utf8');
  html = html.replace(/[ \t]*<!-- stamp:begin[\s\S]*?<!-- stamp:end -->\r?\n/, '');
  // the import map has to come before the first module script
  html = html.replace(/(\s*)(<script src="assets\/assets\.js)/, `$1${map.replace(/\n/g, '$1')}$1$2`);
  html = html.replace(/src="src\/main\.js(\?v=\w+)?"/, `src="src/main.js?v=${hash('src/main.js')}"`);
  html = html.replace(/src="assets\/assets\.js(\?v=\w+)?"/,`src="assets/assets.js?v=${hash('assets/assets.js')}"`);
  for (const css of ['styles/main.css', 'styles/ui2.css']) {
    html = html.replace(new RegExp(`href="${css}(\\?v=\\w+)?"`), `href="${css}?v=${hash(css)}"`);
  }
  return html;
}

const current = readFileSync(join(root, 'index.html'), 'utf8');
const next = stamped();
if (process.argv.includes('--check')) {
  if (current !== next) { console.error('index.html is not stamped for the current files: run npm run stamp'); process.exit(1); }
  console.log('index.html stamp is current');
} else {
  writeFileSync(join(root, 'index.html'), next);
  console.log(`stamped ${Object.keys(JSON.parse(next.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports).length} modules`);
}
