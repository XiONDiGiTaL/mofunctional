#!/usr/bin/env node
/**
 * Rebuild the English catalog from the source and report translation coverage.
 *
 *   node scripts/i18n-catalog.mjs            writes src/i18n/catalog.js, prints coverage
 *   node scripts/i18n-catalog.mjs --todo es  also writes i18n-todo-es.tsv (key, English) of
 *                                            every line that has no Spanish yet
 *
 * Every string literal in src/ that reads like prose is a catalog line; template literals keep
 * their holes as {0}, {1}... The debug menu and console messages are left out.
 */
import fs from 'node:fs';
import { walkFiles, entries } from './i18n-scan.mjs';
import { keyOf } from '../src/i18n/i18n.js';

const SKIP_FILES = [/src[\\/]i18n[\\/]/, /src[\\/]ui[\\/]debug\.js$/];
const lines = new Set();
for (const f of walkFiles('src')) {
  if (SKIP_FILES.some((r) => r.test(f))) continue;
  for (const e of entries(fs.readFileSync(f, 'utf8'))) {
    if (/^\[[a-z]+\]/i.test(e)) continue;                 // console messages
    if (/^(\*|\/\/|\[data-|uniform |varying |export |import |const |let |if \(|for \(|return )/.test(e)) continue; // code and comments the scanner caught
    if (/[;{]\s*$|=>|\(g[,)]|g\.toast\(|s\.[a-z]+\.[a-z]+\s*=|===|&&|\|\||Math\.|void|^:/.test(e)) continue;
    if (/^[\w.]+\s*=\s*$/.test(e) || /^line =$/.test(e)) continue;
    if (!/\s/.test(e) && e.length > 40) continue;          // base64, data URIs, long ids
    lines.add(e);
  }
}
// single lowercase words in the markup read like code to the scanner, so they are listed here
const EXTRA = ['automatic', 'autosave', 'cheeks', 'controls', 'daily', 'date', 'followers', 'following', 'gift',
  'girlfriend', 'none', 'pinned', 'posts', 'power', 'rent', 'service', 'shift', 'slots', 'talking', 'yours', 'day {0}',
  'holding', 'nvm', 'asleep', 'gone', 'home', 'inside', 'teaching', 'working', 'live', 'paid', 'risky', 'nearby'];
for (const e of EXTRA) lines.add(e);
const list = [...lines].sort();
fs.writeFileSync('src/i18n/catalog.js', `/** Generated by scripts/i18n-catalog.mjs: every English line the game can show. Do not edit. */\nexport const CATALOG = ${JSON.stringify(list, null, 0).replace(/","/g, '",\n"')};\n`);

for (const id of ['es', 'de']) {
  let map = {};
  try { map = (await import(`../src/i18n/${id}.js`)).default; } catch { /* none yet */ }
  const have = list.filter((l) => map[keyOf(l)]).length;
  console.log(`${id}: ${have}/${list.length} lines translated (${Math.round((have / list.length) * 100)}%)`);
  const todo = process.argv.indexOf('--todo');
  if (todo >= 0 && process.argv[todo + 1] === id) {
    fs.writeFileSync(`i18n-todo-${id}.tsv`, list.filter((l) => !map[keyOf(l)]).map((l) => `${keyOf(l)}\t${l.replace(/\t/g, ' ')}`).join('\n'));
  }
}
console.log(`catalog: ${list.length} lines`);
